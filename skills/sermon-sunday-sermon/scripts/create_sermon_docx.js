function p(text, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text, font: "맑은 고딕", size: 24, ...opts })],
    spacing: { after: 160 },
    ...( opts.alignment ? { alignment: opts.alignment } : {} )
  });
}

function heading1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    children: [new TextRun({ text, font: "맑은 고딕", size: 32, bold: true, color: "1F3864" })],
    spacing: { before: 400, after: 200 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "1F3864", space: 4 } }
  });
}

function heading2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    children: [new TextRun({ text, font: "맑은 고딕", size: 26, bold: true, color: "2E4057" })],
    spacing: { before: 300, after: 160 }
  });
}

function subLabel(text) {
  return new Paragraph({
    children: [new TextRun({ text, font: "맑은 고딕", size: 24, bold: true, color: "C00000" })],
    spacing: { before: 240, after: 100 }
  });
}

function quoteBlock(text) {
  return new Paragraph({
    children: [new TextRun({ text, font: "맑은 고딕", size: 24, italics: true, color: "404040" })],
    spacing: { after: 160 },
    indent: { left: 600, right: 600 },
    border: { left: { style: BorderStyle.SINGLE, size: 16, color: "C00000", space: 8 } }
  });
}

function connector(text) {
  return new Paragraph({
    children: [new TextRun({ text: "→ " + text, font: "맑은 고딕", size: 24, bold: true, color: "1F6A8C" })],
    spacing: { before: 200, after: 200 },
    alignment: AlignmentType.RIGHT
  });
}

function empty() {
  return new Paragraph({ children: [new TextRun("")], spacing: { after: 80 } });
}

